from fastapi import status
from fastapi import Request
from fastapi.encoders import jsonable_encoder
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel
from pydantic import Field
from typing import Any, Dict, Optional
from app.core.exceptions import DomainException

class ProblemDetails(BaseModel):
    type: str = Field(
        default = "about:blank",
        description="A URI reference identifying the problem type.",
    )
    title: str = Field(
        ..., description="Short summary of the problem type."
    )
    status: int = Field(
        ..., description="HTTP status code generated by the server."
    )
    detail: str = Field(
        ..., description="Human-readable explanation specific to this occurrence."
    )
    instance: Optional[str] = Field(
        default=None, description="URI path identifying the specific request instance."
    )
    invalid_params: Optional[list[Dict[str, Any]]] = Field(
        default=None, description="Field-level validation error details."
    )

async def domain_exception_handler(
    request: Request,
    exception: DomainException,
) -> JSONResponse:

    problem = ProblemDetails(
        type="about:blank",
        title=exception.title,
        status=exception.status_code,
        detail=exception.message,
        instance=request.url.path,
    )

    headers = {}

    if exception.status_code == status.HTTP_401_UNAUTHORIZED:
        headers["WWW-Authenticate"] = "Bearer"

    return JSONResponse(
        status_code=exception.status_code,
        content=jsonable_encoder(problem),
        media_type="application/problem+json",
        headers=headers,
    )


async def validation_exception_handler(
        request: Request,
        exception: RequestValidationError
) -> JSONResponse:
    invalid_params = [
        {
        "name": "->".join(str(loc) for loc in error["loc"]),
        "reason": error["msg"]
        } 
        for error in exception.errors()
    ]

        
    problem = ProblemDetails(
        type="about:blank",
        title="Validation Error",
        status=status.HTTP_422_UNPROCESSABLE_CONTENT,
        detail="The request body or parameters failed validation.",
        instance=request.url.path,
        invalid_params=invalid_params,
    )

    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
        content=jsonable_encoder(problem),
        media_type="application/problem+json",
    )


async def unhandled_exception_handler(
        request: Request, exception: Exception
) -> JSONResponse:


    problem = ProblemDetails(
        type="about:blank",
        title="Internal Server Error",
        status=status.HTTP_500_INTERNAL_SERVER_ERROR,
        detail="An unexpected error occurred.",
        instance=request.url.path,
    )
    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content=jsonable_encoder(problem),
        media_type="application/problem+json",
    )